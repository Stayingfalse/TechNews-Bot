GLYPHS: dict[str, np.ndarray] = {}
for ch, bits in _G.items():
    assert len(bits) == 35, ch
    GLYPHS[ch] = np.array([c == "#" for c in bits], dtype=bool).reshape(H, W)


def width(text: str, scale: int = 1) -> int:
    n = len(text)
    return max(0, (n * (W + GAP) - GAP) * scale)


def mask(text: str, scale: int = 1) -> np.ndarray:
    """A boolean mask of the text, `scale` pixels per font pixel."""
    out = np.zeros((H * scale, max(1, width(text, scale))), dtype=bool)
    x = 0
    for ch in text.upper():
        g = GLYPHS.get(ch, GLYPHS["?"])
        if scale > 1:
            g = g.repeat(scale, 0).repeat(scale, 1)
        out[:, x:x + W * scale] |= g
        x += (W + GAP) * scale
    return out
